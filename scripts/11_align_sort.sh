#!/usr/bin/env bash

# Enable strict error handling:
# -e: Exit immediately if a command returns a non-zero status.
# -u: Treat the use of an unset variable as an error.
# -o pipefail: Make a pipeline fail if any command within it fails,
#              rather than only checking the exit status of the last command.
#
# These options help detect errors and prevent the script from
# reporting success when an earlier pipeline command has failed.
set -euo pipefail

# Define the root directory of the project.
# $HOME is an environment variable representing the current user's home directory.
PROJECT_DIR="$HOME/intro-to-seq"

# Define the directory containing the project's data.
DATA_DIR="${PROJECT_DIR}/data"

# Define the directory containing the trimmed paired-end reads.
# These FASTQ files are expected to have been generated by the trimming step of the pipeline.
TRIMMED_DIR="${DATA_DIR}/trimmed"

# Define the directory containing the reference genome and the Bowtie2 index files.
REF_DIR="${DATA_DIR}/ref_genome"

# Define the directory where alignment results and logs will be stored.
ALIGNED_DIR="${DATA_DIR}/alignments"

# Creat the folder if don't existe :
mkdir -p "$ALIGNED_DIR"

# ============================================================
# Step 1: Align trimmed reads against the reference genome
# ============================================================
bowtie2 \
    -x "${REF_DIR}/ecoli-strK12-MG1655.fasta" \
    -1 "${TRIMMED_DIR}/trimmed_SRR519926_1.fastq" \
    -2 "${TRIMMED_DIR}/trimmed_SRR519926_2.fastq" \
    2> "${ALIGNED_DIR}/bowtie2_SRR519926.log" \
    | samtools sort - \
    | samtools view -bh - \
    > "${ALIGNED_DIR}/SRR519926.sorted.mapped.frompipe.bam"

# Run Bowtie2 to align paired-end sequencing reads against
# the E. coli reference genome.
#
# -x: Specify the basename of the Bowtie2 reference index.
#     The index must have been created previously with
#     bowtie2-build.
#
# -1: Specify the FASTQ file containing the first read
#     of each paired-end read pair.
#
# -2: Specify the FASTQ file containing the second read
#     of each paired-end read pair.
#
# Bowtie2 writes SAM-formatted alignment records to standard
# output (stdout). Its alignment summary and diagnostic
# messages are written to standard error (stderr).
#
# 2> redirects stderr to a log file. This saves the Bowtie2
# alignment summary and messages without mixing them with
# the SAM records sent to the next command.

# ============================================================
# Step 2: Sort the alignment records
# ============================================================
# samtools sort - \
#     |

# Pass the SAM output from Bowtie2 directly to samtools sort
# using a pipe. This avoids creating an intermediate SAM file.
#
# sort: Sort alignment records by genomic coordinates by default.
# -: Read input from standard input (stdin).
#
# samtools sort produces coordinate-sorted BAM output by default
# in current Samtools versions.

# ============================================================
# Step 3: Convert the sorted alignments to BAM format
# ============================================================
# samtools view -bh - \
#     > "${ALIGNED_DIR}/SRR519926.sorted.mapped.frompipe.bam"

# Pass the sorted alignment stream to samtools view.
#
# -b: Write output in BAM format (binary alignment format).
# -h: Include the SAM header in the output.
# -: Read alignment data from standard input.
#
# Note: samtools sort already produces BAM output by default.
# Therefore, this conversion step is generally redundant.
#
# The final BAM file is written using output redirection below.



echo "[INFO] Alignment, sorting and conversion to BAM format complete."

